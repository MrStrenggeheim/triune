"""Native provenance requires structured origins, independently of human text."""

from omnigent.native.communication import (
    is_native_question_answer,
    native_message_text,
    native_peer_metadata,
    peer_model_content,
)


def test_peer_name_and_clean_report_are_preserved() -> None:
    origin = {
        "kind": "peer",
        "name": "Curie",
        "from": "native-agent",
        "senderTaskId": "task-1",
        "handback": True,
        "handbackReportText": "Clean result",
    }
    metadata = native_peer_metadata(origin, "message-1")["communication"]
    assert metadata["source_agent_name"] == "Curie"
    assert metadata["source_agent_id"] == "task-1"
    assert metadata["task_id"] == "task-1"
    assert metadata["source_conversation_id"] is None
    assert native_message_text(origin, "generic wrapper") == "Clean result"


def test_task_notification_is_context_but_literal_human_markup_is_unchanged() -> None:
    text = "<task-notification>quoted by the user</task-notification>"
    assert native_peer_metadata({"kind": "task-notification", "runId": "shell-1"}, "m1") == {
        "is_meta": True
    }
    assert native_peer_metadata(None, "m2") == {}
    assert native_message_text(None, text) == text


def test_native_human_answer_identity_is_metadata_not_text() -> None:
    identity = "omnigent-codex-question:" + "a" * 64
    assert is_native_question_answer(identity)
    assert not is_native_question_answer(None)
    assert not is_native_question_answer("Please print " + identity)
    assert not is_native_question_answer("omnigent-input:" + "b" * 32)


def test_framework_model_input_preserves_authorship_without_changing_human_text() -> None:
    from omnigent.entities.communication import MessageCommunication

    content = [{"type": "input_text", "text": "Continue existing work."}]
    assert peer_model_content(content, None) is content
    origin = MessageCommunication(
        kind="system",
        message_id="a" * 32,
        destination_conversation_id="chat",
        source_title="Session resumed",
    )
    framed = peer_model_content(content, origin)
    assert "generated by the application" in framed[0]["text"]
    assert origin.message_id in framed[0]["text"]
    assert framed[1:] == content
