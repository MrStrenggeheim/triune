import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import {
  ARTIFACT_TOKEN_ALIASES,
  DESIGN_COMPONENTS,
  DESIGN_CONTRACT_VERSION,
  DESIGN_DARK_ROLES,
  DESIGN_DARK_SEMANTIC_TOKENS,
  DESIGN_EXCEPTIONS,
  DESIGN_RADII,
  DESIGN_ROLES,
  DESIGN_SEMANTIC_TOKENS,
  DENSITY_TOKENS,
} from "../src/lib/designContract.ts";
import { DEFAULT_PALETTE, PALETTES, PALETTE_TOKEN_CSS_NAMES } from "../src/lib/themePalette.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const path = (name) => resolve(root, name);
const outputs = {
  palettes: path("src/themePalettes.generated.css"),
  design: path("src/designContract.generated.css"),
  density: path("src/listDensity.generated.css"),
  artifact: path("src/artifacts/kit/triune-artifact.css"),
  manifest: path("src/artifacts/kit/manifest.json"),
};
const check = process.argv.slice(2).includes("--check");
const extra = process.argv.slice(2).filter((argument) => argument !== "--check");
if (extra.length) throw new Error(`Unknown arguments: ${extra.join(", ")}`);

const rule = (selector, declarations) =>
  `${selector} {\n${declarations.map(([name, value]) => `  ${name}: ${value};`).join("\n")}\n}`;
const px = (values) => Object.entries(values).map(([name, value]) => [`--${name}`, `${value}px`]);
const backgroundKeys = new Set(["shellBackground", "sidebarBackground"]);

function selectorFor(palette, mode) {
  if (palette.id === "omni")
    return mode === "light" ? ":root:not(.dark):not([data-theme])" : ".dark:not([data-theme])";
  return mode === "light"
    ? `:root:not(.dark)[data-theme="${palette.id}"]`
    : `.dark[data-theme="${palette.id}"]`;
}

function paletteRules(palette, mode) {
  const selector = selectorFor(palette, mode);
  const tokens = palette.tokens[mode];
  const declarations = Object.entries(PALETTE_TOKEN_CSS_NAMES)
    .filter(([key]) => !backgroundKeys.has(key))
    .map(([key, cssName]) => [`--${cssName}`, tokens[key]]);
  return [
    rule(selector, declarations),
    rule(`${selector} .app-shell`, [["background", tokens.shellBackground]]),
    rule(`${selector} .conversations-sidebar`, [["background", tokens.sidebarBackground]]),
  ];
}

function customRules(mode) {
  const selector =
    mode === "light" ? ':root:not(.dark)[data-theme="custom"]' : '.dark[data-theme="custom"]';
  const declarations = Object.entries(PALETTE_TOKEN_CSS_NAMES)
    .filter(([key]) => !backgroundKeys.has(key))
    .map(([, cssName]) => [`--${cssName}`, `var(--custom-${mode}-${cssName})`]);
  return [
    rule(selector, declarations),
    rule(`${selector} .app-shell`, [["background", `var(--custom-${mode}-shell-background)`]]),
    rule(`${selector} .conversations-sidebar`, [
      ["background", `var(--custom-${mode}-sidebar-background)`],
    ]),
  ];
}

function paletteSource() {
  const rules = PALETTES.flatMap((palette) =>
    ["light", "dark"].flatMap((mode) => paletteRules(palette, mode)),
  );
  rules.push(...["light", "dark"].flatMap(customRules));
  return `/* Generated by scripts/generate-theme-palettes.mjs. */\n\n${rules.join("\n\n")}\n`;
}

function designSource() {
  const radii = [
    ["--radius-sm", `${DESIGN_RADII.sm}px`],
    ["--radius-md", `${DESIGN_RADII.md}px`],
    ["--radius-lg", `${DESIGN_RADII.lg}px`],
    ["--radius-tooltip", `${DESIGN_RADII.tooltip}px`],
    ["--radius-4xl", "calc(var(--radius) * 2.6)"],
  ];
  const vars = [
    ["--radius", "0.5rem"],
    ...Object.entries(DESIGN_SEMANTIC_TOKENS).map(([name, value]) => [`--${name}`, value]),
    ...Object.entries(DESIGN_ROLES).map(([name, value]) => [`--${name}`, value]),
  ];
  const dark = [
    ...Object.entries(DESIGN_DARK_SEMANTIC_TOKENS).map(([name, value]) => [`--${name}`, value]),
    ...Object.entries(DESIGN_DARK_ROLES).map(([name, value]) => [`--${name}`, value]),
  ];
  return `/* Generated by scripts/generate-theme-palettes.mjs. */\n\n${rule("@theme inline", radii)}\n\n${rule(":root", vars)}\n\n${rule(".dark", dark)}\n`;
}

function densitySource() {
  return `/* Generated by scripts/generate-theme-palettes.mjs. */\n\n${rule(
    ':root, [data-list-density="comfortable"]',
    px(DENSITY_TOKENS.comfortable),
  )}\n\n${rule('[data-list-density="compact"]', px(DENSITY_TOKENS.compact))}\n`;
}

const aliasByToken = Object.fromEntries(
  Object.entries(ARTIFACT_TOKEN_ALIASES).map(([alias, token]) => [token, alias]),
);
Object.assign(aliasByToken, {
  "--foreground": "--ta-text",
  "--muted": "--ta-control-surface",
  "--primary": "--ta-primary",
  "--secondary": "--ta-secondary",
  "--secondary-foreground": "--ta-text",
});
const artifactValue = (value) =>
  value.replace(/var\((--[a-z0-9-]+)\)/g, (_, token) => {
    if (!aliasByToken[token]) throw new Error(`No artifact alias for ${token}`);
    return `var(${aliasByToken[token]})`;
  });

function artifactRules(mode) {
  const palette = PALETTES.find(({ id }) => id === DEFAULT_PALETTE);
  if (!palette) throw new Error(`Missing default palette ${DEFAULT_PALETTE}`);
  const tokens = palette.tokens[mode];
  const base =
    mode === "light"
      ? [
          ["--ta-primary", tokens.primary],
          ["--ta-primary-foreground", tokens.primaryForeground],
          ["--ta-brand", tokens.primary],
          ["--ta-content", tokens.background],
          ["--ta-text", tokens.foreground],
          ["--ta-muted", tokens.mutedForeground],
          ["--ta-control-surface", tokens.muted],
          ["--ta-secondary", tokens.secondary],
          ["--ta-border", tokens.border],
          ["--ta-ring", tokens.primary],
          ["--ta-success", DESIGN_SEMANTIC_TOKENS.success],
          ["--ta-warning", DESIGN_SEMANTIC_TOKENS.warning],
          ["--ta-error", DESIGN_SEMANTIC_TOKENS.destructive],
          ["--ta-info", DESIGN_SEMANTIC_TOKENS.info],
          ["--ta-radius-sm", `${DESIGN_RADII.sm}px`],
          ["--ta-radius-md", `${DESIGN_RADII.md}px`],
          ["--ta-radius-lg", `${DESIGN_RADII.lg}px`],
          ["--ta-radius-tooltip", `${DESIGN_RADII.tooltip}px`],
          ["--ta-radius-base", ".5rem"],
          ["--ta-radius-4xl", "calc(var(--ta-radius-base) * 2.6)"],
          ["--ta-space-1", "4px"],
          ["--ta-space-2", "8px"],
          ["--ta-space-3", "12px"],
          ["--ta-space-4", "16px"],
          ["--ta-space-6", "24px"],
          ["--ta-ui", "13px"],
          ["--ta-small", "calc(var(--ta-ui) * 0.9)"],
          [
            "--ta-font",
            'ui-sans-serif, system-ui, sans-serif, "Apple Color Emoji", "Segoe UI Emoji", "Segoe UI Symbol", "Noto Color Emoji"',
          ],
          ["--ta-target", "24px"],
          ["color-scheme", "light"],
          ["--ta-row-min", `${DENSITY_TOKENS.comfortable["list-row-min-height"]}px`],
          ["--ta-row-y", `${DENSITY_TOKENS.comfortable["list-row-padding-block"]}px`],
          ["--ta-row-x", `${DENSITY_TOKENS.comfortable["list-row-padding-inline"]}px`],
        ]
      : [
          ["--ta-primary", tokens.primary],
          ["--ta-primary-foreground", tokens.primaryForeground],
          ["--ta-brand", tokens.primary],
          ["--ta-content", tokens.background],
          ["--ta-text", tokens.foreground],
          ["--ta-muted", tokens.mutedForeground],
          ["--ta-control-surface", tokens.muted],
          ["--ta-secondary", tokens.secondary],
          ["--ta-border", tokens.border],
          ["--ta-ring", tokens.primary],
          ["--ta-error", DESIGN_DARK_SEMANTIC_TOKENS.destructive],
          ["color-scheme", "dark"],
        ];
  const source = mode === "light" ? DESIGN_ROLES : DESIGN_DARK_ROLES;
  const roles = Object.entries(source)
    .filter(([name]) => aliasByToken[`--${name}`])
    .map(([name, value]) => [aliasByToken[`--${name}`], artifactValue(value)])
    .filter(([alias, value]) => value !== `var(${alias})`);
  return [...base, ...roles];
}

function artifactHeader() {
  const dark = artifactRules("dark");
  const compact = [
    ["--ta-row-min", `${DENSITY_TOKENS.compact["list-row-min-height"]}px`],
    ["--ta-row-y", `${DENSITY_TOKENS.compact["list-row-padding-block"]}px`],
    ["--ta-row-x", `${DENSITY_TOKENS.compact["list-row-padding-inline"]}px`],
  ];
  return `/* Generated first-party Triune artifact kit. PolyForm Noncommercial 1.0.0.
 * Required Notice: Copyright 2026 MrStrenggeheim. Triune (https://github.com/MrStrenggeheim/triune).
 * Self-contained native adapters; no application stylesheet or runtime required.
 */
${rule(".ta-root", artifactRules("light"))}
${rule('.ta-root[data-theme="dark"]', dark)}
@media (prefers-color-scheme: dark) {
${rule('.ta-root:not([data-theme="light"]):not([data-theme="dark"])', dark)}
}
${rule('.ta-root[data-density="compact"]', compact)}
`;
}

const pretty = async (source, output, parser) =>
  format(source, { ...(await resolveConfig(output)), parser });
const artifactSource = await readFile(path("src/artifacts/kit/triune-artifact.source.css"), "utf8");
const generated = {
  [outputs.palettes]: await pretty(paletteSource(), outputs.palettes, "css"),
  [outputs.design]: await pretty(designSource(), outputs.design, "css"),
  [outputs.density]: await pretty(densitySource(), outputs.density, "css"),
  [outputs.artifact]: await pretty(
    `${artifactHeader()}\n${artifactSource}`,
    outputs.artifact,
    "css",
  ),
};
const [javascript, icons] = await Promise.all([
  readFile(path("src/artifacts/kit/triune-artifact.js"), "utf8"),
  readFile(path("src/artifacts/kit/triune-icons.svg"), "utf8"),
]);
const hash = (source) => createHash("sha256").update(source).digest("hex");
const asset = (source) => ({ bytes: Buffer.byteLength(source), sha256: hash(source) });
const manifest = {
  kit_id: "triune-artifact",
  version: DESIGN_CONTRACT_VERSION,
  public_base_path: `artifacts/kit/${DESIGN_CONTRACT_VERSION}/`,
  namespace: "ta-* / --ta-*",
  assets: {
    "triune-artifact.css": asset(generated[outputs.artifact]),
    "triune-artifact.js": { ...asset(javascript), optional: true },
    "triune-icons.svg": {
      ...asset(icons),
      license: "Lucide ISC; see LUCIDE-LICENSE.txt",
    },
  },
  budgets_bytes: { css: 20480, javascript: 12288 },
  runtime: {
    dependencies: [],
    external_cdns: false,
    entry: "window.TriuneArtifact.init(root)",
    automatic_mount: "[data-ta-init]",
    network: "none",
  },
  native_behavior: {
    supported: ["tabs", "disclosure", "arrowless tooltip", "theme control", "density control"],
    parity_limits: [
      "Native adapters do not import React or Radix behavior.",
      "Native select popups and radio paint remain browser-owned.",
      "Content tabs do not reproduce dock layout, pinning, or selection strips.",
      "Host tokens override fallbacks through getArtifactThemeVariables(root).",
    ],
  },
  components: DESIGN_COMPONENTS,
  exceptions: DESIGN_EXCEPTIONS,
  token_aliases: ARTIFACT_TOKEN_ALIASES,
};
generated[outputs.manifest] = await pretty(
  `${JSON.stringify(manifest, null, 2)}\n`,
  outputs.manifest,
  "json",
);
// Vite copies public/ into the installed SPA, giving agents a stable first-party discovery path.
const publicRoot = path(`public/artifacts/kit/${DESIGN_CONTRACT_VERSION}`);
for (const [name, source] of Object.entries({
  "triune-artifact.css": generated[outputs.artifact],
  "triune-artifact.js": javascript,
  "triune-icons.svg": icons,
  "manifest.json": generated[outputs.manifest],
  "LUCIDE-LICENSE.txt": await readFile(path("src/artifacts/kit/LUCIDE-LICENSE.txt"), "utf8"),
  "LICENSE.txt": await readFile(
    resolve(root, "../LICENSES/PolyForm-Noncommercial-1.0.0.txt"),
    "utf8",
  ),
}))
  generated[resolve(publicRoot, name)] = source;
generated[path("public/artifacts/kit/manifest.json")] = await pretty(
  JSON.stringify({
    kit_id: manifest.kit_id,
    version: manifest.version,
    manifest: `./${DESIGN_CONTRACT_VERSION}/manifest.json`,
  }),
  path("public/artifacts/kit/manifest.json"),
  "json",
);
for (const required of [
  "--ta-control-surface:",
  "--ta-space-1:",
  "--ta-ui: 13px",
  "--ta-small:",
  "--ta-font:",
  "--ta-target: 24px",
  "color-scheme: dark",
]) {
  if (!generated[outputs.artifact].includes(required))
    throw new Error(`Artifact fallback is missing ${required}`);
}
if (generated[outputs.artifact].includes("--ta-control-surface: var(--ta-control-surface)"))
  throw new Error("Artifact control surface fallback is self-referential");
if (manifest.assets["triune-artifact.css"].bytes > manifest.budgets_bytes.css)
  throw new Error("Artifact CSS exceeds 20 KiB");
if (manifest.assets["triune-artifact.js"].bytes > manifest.budgets_bytes.javascript)
  throw new Error("Artifact helper exceeds 12 KiB");

const stale = await Promise.all(
  Object.entries(generated).map(async ([output, source]) => {
    if (!check) {
      await mkdir(dirname(output), { recursive: true });
      await writeFile(output, source);
      console.log(`Generated ${output}`);
      return false;
    }
    const different = (await readFile(output, "utf8").catch(() => "")) !== source;
    if (different) console.error(`${output.slice(root.length + 1)} is stale.`);
    return different;
  }),
);
if (stale.some(Boolean)) {
  console.error("Run `just generate-theme-palettes`.");
  process.exitCode = 1;
}
